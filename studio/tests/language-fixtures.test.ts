// The shared language fixtures, generated by scripts/language_fixtures.py. The
// platform formats numbers for concat and join exactly as JavaScript's
// String(x), so Studio previews match it.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { schemaTypes, typeLabel } from "../src/app/forms/core/scope";

const fixture = (name: string) =>
  JSON.parse(
    readFileSync(
      resolve(import.meta.dirname, "fixtures/language", name),
      "utf8",
    ),
  );

describe("shared language fixtures", () => {
  it("formats every concat and join value as JavaScript does", () => {
    const { cases } = fixture("text-conversion.json") as {
      cases: { value: string | number | boolean; text: string }[];
    };
    expect(cases.length).toBeGreaterThan(10);
    for (const { value, text } of cases) expect(String(value), text).toBe(text);
  });
  it("accepts exactly the valid instance keys with the published pattern", () => {
    const { pattern, valid, invalid } = fixture("instance-keys.json") as {
      pattern: string;
      valid: { key: string; node_id: string }[];
      invalid: { key: string }[];
    };
    const instanceKey = new RegExp(`^(?:${pattern})$`, "u");
    for (const { key, node_id } of valid) {
      expect(instanceKey.test(key), key).toBe(true);
      expect(key.startsWith(node_id), key).toBe(true);
      expect(node_id, key).not.toMatch(/[[\]#~]/);
    }
    for (const { key } of invalid)
      expect(instanceKey.test(key), key).toBe(false);
    expect(invalid.length).toBeGreaterThan(10);
  });
  it("maps every concat to template segments and saves them normalized", () => {
    type Expression = Record<string, unknown>;
    type Segment =
      | { kind: "text"; text: string }
      | { kind: "placeholder"; expression: Expression };
    const { cases } = fixture("template-segments.json") as {
      cases: {
        name: string;
        expression: Expression;
        segments: Segment[] | null;
        saved: Expression | null;
      }[];
    };
    expect(cases.length).toBeGreaterThan(8);
    const isText = (value: unknown): value is { literal: string } =>
      typeof value === "object" &&
      value !== null &&
      Object.keys(value).length === 1 &&
      typeof (value as { literal?: unknown }).literal === "string";
    for (const { name, expression, segments, saved } of cases) {
      const op = (expression as { op?: { name?: string; args?: unknown[] } })
        .op;
      if (segments === null) {
        expect(op?.name === "concat", name).toBe(false);
        expect(saved, name).toBeNull();
        continue;
      }
      // One segment per concat argument: string literals are text, anything else a placeholder.
      expect(
        segments.map((segment) => segment.kind),
        name,
      ).toEqual(
        (op?.args ?? []).map((arg) => (isText(arg) ? "text" : "placeholder")),
      );
      // Saving merges adjacent text, drops empty text and stores text-only templates as one literal.
      const args = (saved as { op?: { args: unknown[] } }).op?.args;
      if (args === undefined) {
        expect(saved, name).toEqual({
          literal: segments
            .map((segment) => (segment.kind === "text" ? segment.text : ""))
            .join(""),
        });
        continue;
      }
      args.forEach((arg, index) => {
        expect(arg, name).not.toEqual({ literal: "" });
        if (index > 0)
          expect(isText(arg) && isText(args[index - 1]), name).toBe(false);
      });
    }
  });
  it("names loop data by the loop that owns it and labels types as Studio does", () => {
    type Entry = {
      ref: string;
      source: string;
      loop?: string;
      path: string[];
      schema: Record<string, unknown>;
      types: string[];
      typeLabel: string;
    };
    const { cases } = fixture("scope.json") as {
      cases: {
        name: string;
        result: { found: boolean; entries: Entry[] };
      }[];
    };
    expect(cases.length).toBeGreaterThan(5);
    expect(cases.some(({ result }) => !result.found)).toBe(true);
    for (const { name, result } of cases) {
      const loops = result.entries.filter((entry) => entry.loop !== undefined);
      // The innermost loop is read as /item and /index; enclosing loops by ID.
      const innermost = loops.find((entry) => entry.ref === "/item")?.loop;
      for (const entry of result.entries) {
        expect(typeLabel(entry.schema), `${name}: ${entry.ref}`).toBe(
          entry.typeLabel,
        );
        expect(schemaTypes(entry.schema), `${name}: ${entry.ref}`).toEqual(
          entry.types,
        );
        if (entry.source === "item" || entry.source === "index") {
          const base = entry.loop === innermost ? "" : `/loops/${entry.loop}`;
          const root = `${base}/${entry.source}`;
          expect(entry.ref, name).toBe([root, ...entry.path].join("/"));
        } else expect(entry.loop, name).toBeUndefined();
      }
    }
  });
  it("names every undo phase at a canonical instance key of its step", () => {
    const { pattern } = fixture("instance-keys.json") as { pattern: string };
    const instanceKey = new RegExp(`^(?:${pattern})$`, "u");
    const shared = fixture("transactions.json") as {
      phase_keys: { key: string; instance_key: string; phase: string }[];
      not_phase_keys: string[];
      states: string[];
      state_order: string[];
      terminal_states: string[];
      unsettled_states: string[];
      cases: {
        name: string;
        diagnostics: { code: string; path: string; severity: string }[];
      }[];
    };
    const suffix: Record<string, string> = {
      confirm: "confirm",
      cancel: "cancel",
      compensate: "undo",
    };
    for (const { key, instance_key, phase } of shared.phase_keys) {
      expect(instanceKey.test(key), key).toBe(true);
      expect(key, key).toBe(`${instance_key}#${suffix[phase]}`);
    }
    for (const key of shared.not_phase_keys)
      expect(/#(confirm|cancel|undo)$/.test(key), key).toBe(false);
    expect([...shared.state_order].sort()).toEqual([...shared.states].sort());
    expect(
      [...shared.terminal_states, ...shared.unsettled_states].sort(),
    ).toEqual([...shared.states].sort());
    for (const { name, diagnostics } of shared.cases)
      for (const { code, severity } of diagnostics) {
        expect(code, name).toMatch(/^WV-COMP-(TXN_[A-Z_]+|[A-Z_]+)$/);
        expect(["error", "warning", "info"], name).toContain(severity);
      }
  });
  it("publishes the manifest with Studio marks on every entry", () => {
    const { manifest } = fixture("manifest.json") as {
      manifest: Record<string, { studio: string }[]>;
    };
    for (const group of [
      "step_kinds",
      "operators",
      "workflow_fields",
      "step_fields",
    ])
      for (const entry of manifest[group])
        expect(["ready", "pending"]).toContain(entry.studio);
  });
});
