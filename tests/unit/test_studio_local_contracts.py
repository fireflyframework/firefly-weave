@pytest.mark.parametrize(
    "target",
    [
        {"mode": "workflow", "stepId": "send"},
        {"mode": "step"},
        {"mode": "before", "instanceKey": "send[1]"},
        {"mode": "step", "stepId": "send", "instanceKey": "notify[1]"},
        {"mode": "step", "stepId": "send", "instanceKey": "send[01]"},
    ],
)
def test_a_target_names_one_step_and_only_its_instances(target):
    with pytest.raises(ValidationError):
        lc.ExecuteRequest.model_validate_json(json.dumps({**EXECUTE_REQUEST, "target": target}))


@pytest.mark.parametrize("case", STEP_KEYS, ids=lambda case: repr(case["key"]))
def test_targets_trace_entries_and_mocks_take_every_shared_key_of_their_step(case):
    target = {"mode": "step", "stepId": case["node_id"], "instanceKey": case["key"]}
    entry = {"index": 0, "nodeId": case["node_id"], "instanceKey": case["view"]["instance_key"]}
    request = {**EXECUTE_REQUEST, "target": target, "mocks": {f"node:{case['key']}": {}}}
    assert lc.ExecuteRequest.model_validate_json(json.dumps(request)).target.instanceKey == case["key"]
    trace = lc.TraceEntry.model_validate_json(json.dumps({**entry, "kind": "action", "status": "completed"}))
    assert trace.instanceKey == case["view"]["instance_key"]


