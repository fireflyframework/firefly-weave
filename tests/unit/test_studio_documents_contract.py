def doc(**fields):
    return {**copy.deepcopy(MINIMAL), **copy.deepcopy(fields)}


def ecmascript_pattern(validator, pattern, instance, schema):
    """JSON Schema patterns are ECMAScript: a final "$" matches only at the end, not before a trailing newline."""
    if validator.is_type(instance, "string") and re.search(re.sub(r"(?<!\\)\$$", r"\\Z", pattern), instance) is None:
        yield SchemaViolation(f"{instance!r} does not match {pattern!r}")


EcmaScriptValidator = validators.extend(Draft202012Validator, {"pattern": ecmascript_pattern})


def schema_accepts(document) -> bool:
    validator = EcmaScriptValidator(
        documents.studio_test_data_schema(), format_checker=Draft202012Validator.FORMAT_CHECKER
    )
    return validator.is_valid(document)


def model_accepts(document) -> bool:
    try:
        documents.StudioTestData.model_validate_json(json.dumps(document))
    except ValidationError:
        return False
    return True


