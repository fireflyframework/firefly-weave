def test_test_data_accepts_simulated_failures():
    errors = {
        "submit": FAILURE,
        "lookup[2]": {"code": "WV-TASK-AMBIGUOUS", "outcome": "not_started", "attempts": 0, "source": "manual"},
    }
    document = doc(errors=errors)
    assert schema_accepts(document)
    parsed = documents.parse_test_data(json.dumps(document).encode())
    # Omitted fields stay omitted: the defaults (failed after one attempt) are the reader's, never written back.
    assert parsed.model_dump(mode="json", by_alias=True) == document
    assert parsed.errors is not None
    assert (parsed.errors["submit"].code, parsed.errors["submit"].outcome, parsed.errors["submit"].attempts) == (
        "REQUEST_REFUSED",
        None,
        None,
    )
    assert (parsed.errors["lookup[2]"].outcome, parsed.errors["lookup[2]"].attempts) == ("not_started", 0)


