def test_sidecar_fields_are_camel_case_on_the_wire():
    models = [
        documents.StudioTestData,
        documents.InputEntry,
        documents.PinEntry,
        documents.MockEntry,
        documents.SignalScript,
        documents.SignalTimeout,
        documents.HumanScript,
        documents.HumanExpire,
        documents.AiTurnsEntry,
        documents.AiMemoryMessage,
        documents.CalleeMocks,
        documents.WaitScripts,
    ]
    for model in models:
        for name, field in model.model_fields.items():
            assert re.fullmatch(r"[a-z]+(?:[A-Z][a-z0-9]*)*", field.alias or name), (model.__name__, name)
